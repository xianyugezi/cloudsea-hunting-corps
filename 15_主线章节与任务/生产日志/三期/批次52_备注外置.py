for tag, path, logdir in FILES:
    os.makedirs(logdir, exist_ok=True)
    t = io.open(path, encoding='utf-8').read()
    lines = t.split('\n')
    start = None
    for i, l in enumerate(lines):
        if '批次状态表' in l:
            start = i
    n_mig = 0
    for i in range(start, len(lines)):
        m = re.match(r'^\|\s*(\d+)\s*\|([^|]*)\|([^|]*)\|([^|]*)\|(.*)\|\s*$', lines[i])
        if not m:
            continue
        num = int(m.group(1)); name = m.group(2).strip()
        st = m.group(3).strip(); date = m.group(4).strip(); remark = m.group(5).strip()
        if len(remark) <= 40:
            continue
        nn = '%02d' % num
        log = ('# %s批次 %s · %s（执行备注全文）\n\n' % (tag, nn, name)
               + '- **状态**：%s　**完成日期**：%s\n' % (st, date)
               + '- **外置说明**：本文件为《%s》状态表备注列全文，2026-09-07 三期批次 52 库容治理外置；状态表仅留 ≤40 字摘要。\n\n' % path
               + '## 执行备注（全文）\n\n' + remark + '\n')
        io.open(os.path.join(logdir, '批次%s.md' % nn), 'w', encoding='utf-8', newline='\n').write(log)
        new_remark = SUM[num]
        assert len(new_remark) <= 40, (num, len(new_remark))
        lines[i] = '| %d | %s | %s | %s | %s |' % (num, name, st, date, new_remark)
        n_mig += 1
    io.open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print(tag, '外置', n_mig, '条; 新大小', os.path.getsize(path), '字节')

